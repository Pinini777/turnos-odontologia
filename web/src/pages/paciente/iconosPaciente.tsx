export function IconoPrestacion({
  nombre,
  tamano = 20,
}: {
  readonly nombre: string;
  readonly tamano?: number;
}) {
  const n = nombre.toLowerCase();
  if (n.includes('limpieza') || n.includes('profilaxis') || n.includes('blanque')) {
    return <IconoLimpieza tamano={tamano} />;
  }
  if (n.includes('control') || n.includes('revisi') || n.includes('seguim')) {
    return <IconoControl tamano={tamano} />;
  }
  return <IconoConsulta tamano={tamano} />;
}

